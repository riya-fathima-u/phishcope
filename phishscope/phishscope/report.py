"""Turn an analysis dict into a standalone HTML report (no external assets)."""
from html import escape as e

CSS = """
:root{--bg:#eef1f4;--panel:#fff;--ink:#16212b;--muted:#5b6b79;--line:#d5dce3;
--high:#b3261e;--med:#a86400;--low:#4a5b6b;--ok:#1f7a4d;--accent:#0f5c6e}
@media(prefers-color-scheme:dark){:root{--bg:#10171d;--panel:#18222b;--ink:#e6ecf1;--muted:#93a3b1;--line:#2b3946;
--high:#ff8a80;--med:#ffb74d;--low:#9fb0be;--ok:#6fcf97;--accent:#6fc3d6}}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.55 "Segoe UI",system-ui,sans-serif}
main{max-width:980px;margin:0 auto;padding:32px 20px 60px}
h1{font-size:1.5rem;margin:0 0 4px}h2{font-size:1.05rem;margin:32px 0 10px}
.sub{color:var(--muted);margin:0 0 24px;overflow-wrap:anywhere}
.verdict{display:flex;gap:20px;align-items:center;background:var(--panel);border:1px solid var(--line);
border-left:8px solid var(--c);padding:18px 22px;border-radius:6px}
.score{font-size:3rem;font-weight:700;color:var(--c);line-height:1}
.verdict b{font-size:1.25rem}
.panel{background:var(--panel);border:1px solid var(--line);border-radius:6px;overflow-x:auto}
table{border-collapse:collapse;width:100%}
th,td{text-align:left;padding:9px 14px;border-bottom:1px solid var(--line);vertical-align:top;overflow-wrap:anywhere}
tr:last-child td{border-bottom:0}th{width:170px;color:var(--muted);font-weight:600}
.tag{display:inline-block;padding:1px 9px;border-radius:99px;font-size:.8rem;font-weight:600;border:1px solid currentColor}
.high{color:var(--high)}.medium{color:var(--med)}.low{color:var(--low)}.pass{color:var(--ok)}.fail{color:var(--high)}
code{font:.88em ui-monospace,Consolas,monospace;overflow-wrap:anywhere}
.auth{display:flex;gap:12px;flex-wrap:wrap}.auth div{background:var(--panel);border:1px solid var(--line);
border-radius:6px;padding:10px 18px;min-width:130px}.auth span{display:block;color:var(--muted);font-size:.85rem}
footer{margin-top:36px;color:var(--muted);font-size:.85rem}
"""


def _tag(sev):
    return f'<span class="tag {sev}">{e(sev)}</span>'


def _auth_class(v):
    return "pass" if v == "pass" else "fail" if v in ("fail", "softfail", "permerror") else "low"


def build_report(a):
    colour = "var(--high)" if a["score"] >= 50 else "var(--med)" if a["score"] >= 20 else "var(--ok)"
    out = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
           f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
           f"<title>PhishScope report</title><style>{CSS}</style></head><body><main>",
           "<h1>PhishScope report</h1>",
           f"<p class='sub'>{e(a['headers']['File'])}</p>",
           f"<div class='verdict' style='--c:{colour}'><div class='score'>{a['score']}</div>"
           f"<div><b>{e(a['verdict'])}</b><br><span class='sub'>Risk score out of 100. Triage aid, not a final verdict.</span></div></div>"]

    out.append("<h2>Why it scored this way</h2><div class='panel'><table>")
    if a["findings"]:
        for f in a["findings"]:
            out.append(f"<tr><td style='width:90px'>{_tag(f['severity'])}</td>"
                       f"<td><b>{e(f['title'])}</b> (+{f['points']})<br>{e(f['detail'])}</td></tr>")
    else:
        out.append("<tr><td>No red flags found.</td></tr>")
    out.append("</table></div>")

    out.append("<h2>Sender authentication</h2><div class='auth'>")
    for k, v in a["auth"].items():
        out.append(f"<div><span>{k.upper()}</span><b class='{_auth_class(v)}'>{e(v)}</b></div>")
    out.append("</div>")

    out.append("<h2>Headers</h2><div class='panel'><table>")
    for k, v in a["headers"].items():
        out.append(f"<tr><th>{e(k)}</th><td>{e(v)}</td></tr>")
    out.append("</table></div>")

    out.append("<h2>Links (defanged)</h2><div class='panel'><table>")
    if a["links"]:
        for l in a["links"]:
            fl = ", ".join(l["flags"]) or "no flags"
            shown = f"Shown as: {e(l['text'])}<br>" if l["text"] else ""
            out.append(f"<tr><td><code>{e(l['url'])}</code><br>{shown}<small>{e(fl)}</small></td></tr>")
    else:
        out.append("<tr><td>No links found.</td></tr>")
    out.append("</table></div>")

    out.append("<h2>Attachments</h2><div class='panel'><table>")
    if a["attachments"]:
        for t in a["attachments"]:
            fl = ", ".join(t["flags"]) or "no flags"
            out.append(f"<tr><th>{e(t['name'])}</th><td>Real type: {e(t['true_type'])} &middot; {t['size']} bytes"
                       f"<br>SHA-256: <code>{t['sha256']}</code><br>MD5: <code>{t['md5']}</code>"
                       f"<br><small>{e(fl)}</small></td></tr>")
    else:
        out.append("<tr><td>No attachments.</td></tr>")
    out.append("</table></div>")
    out.append("<footer>Generated by PhishScope. The email was never rendered or executed; "
               "attachments were only hashed. Check hashes on VirusTotal before any deeper analysis.</footer>")
    out.append("</main></body></html>")
    return "".join(out)
